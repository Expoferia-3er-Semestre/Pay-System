    public void guardar() {

        try {
            double costo = Double.parseDouble(txtCosto.getText().trim());
            String categoria = txtCategoria.getText().trim();

            if (txtCosto.getText().isBlank() && categoria.isBlank()) {
                JOptionPane.showMessageDialog(null, "Los campos no pueden quedar vacíos.");
                return;
            }

            if (!categoria.matches("^[a-zA-Z\\s]+$")) {
                JOptionPane.showMessageDialog(null, "Solo se permiten letras y espacios en la categoría.");
                return;
            }

            if (costo > 0) {

                    TipoPagoDAO tipoPagoDAO = new TipoPagoDAO();

                    tp.setCosto(costo);
                    tp.setCategoria(categoria);
                    tp.setEstado(true);

                    boolean exito = tipoPagoDAO.agregar(tp);

                    if (exito) {
                        JOptionPane.showMessageDialog(null, "Tipo de pago registrado con éxito.");
                        dispose();
                    }
                    else {
                        JOptionPane.showMessageDialog(null, "Ocurrió un error al registrar el tipo de pago.");
                        dispose();
                    }

            } else JOptionPane.showMessageDialog(null, "El costo debe ser mayor que 0");

        } catch (InputMismatchException e) {
            JOptionPane.showMessageDialog(null, "Solo puede ingresar números al costo.");
        }

    }


