    public void listarPagos() {

        PagoReciboDAO pagoReciboDAO = new PagoReciboDAO();
        java.util.Date dateUtil = dateChooser.getDate();

        if (dateUtil != null) {
            listaPagos = pagoReciboDAO.listarPorFecha(new java.sql.Date (dateUtil.getTime()));

            if (!listaPagos.isEmpty()) {

                for (PagoRecibo pr : listaPagos) {

                    modelo.agregarFila(pr.getIdPagoRecibo(),
                            pr.getMontoTotal(),
                            pr.getMontoPagado(),
                            pr.getFechaPago(),
                            pr.getEstado()
                    );

                }
                dateChooser.cleanup();

        } else {
                JOptionPane.showMessageDialog(null, "No existen pagos realizados en esa fecha.");
            }


        } else {
            JOptionPane.showMessageDialog(null, "Debe escoger una fecha antes de buscar.");
            listaPagos = null;
        }

    }

