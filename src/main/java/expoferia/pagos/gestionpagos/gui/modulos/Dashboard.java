    public void llenarDatos() {

        EstudianteDAO est = new EstudianteDAO();
        estu = est.buscarPorId(pagoSelect.getIdEstudiante());
        RepresentanteDAO rep = new RepresentanteDAO();
        repre = rep.buscarPorCedula(estu.getCedulaRep());

        jLabel2.setText(estu.getNombre1() + " " + estu.getApellido1());
        jLabel3.setText(repre.getNombre1() + " " + repre.getApellido1());
        jLabel4.setText(repre.getCedula());
        jLabel5.setText(estu.getNivel_academico());
        jLabel6.setText(estu.getGrado());

    }

